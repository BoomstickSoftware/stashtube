#!/usr/bin/env node
// Keeps library content out of git. The repo is mirrored to a public GitHub repo, so no tracked
// file may name a performer, studio or indexer from the library (wiki/decisions/github-public-mirror.md);
// such notes live in the gitignored private/ folder.
//
//   node scripts/privacy-check.mjs                      # scan tracked + new (not ignored) files; exit 1 on a hit
//   node scripts/privacy-check.mjs refresh [server]     # rebuild private/denylist.auto.txt from flix's API
//                                                       # (every performer and studio Stash knows; read-only GETs)
//
// Terms: private/denylist.auto.txt (generated) plus private/denylist.txt (by hand: indexers, anything
// else), minus private/allowlist.txt (false positives). One term per line, `#` comments. Matching is
// case-sensitive on whole words. Without a denylist (a fresh clone) the check passes and says so.
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PRIV = join(ROOT, 'private')
const AUTO = join(PRIV, 'denylist.auto.txt')
const MANUAL = join(PRIV, 'denylist.txt')
const ALLOW = join(PRIV, 'allowlist.txt')
const SKIP = [/^pnpm-lock\.yaml$/, /\.(png|jpe?g|gif|webp|ico|woff2?|mp4|pdf)$/i]
const MIN_LEN = 4

const readTerms = (p) =>
  existsSync(p)
    ? readFileSync(p, 'utf8')
        .split('\n')
        .map((l) => l.replace(/#.*/, '').trim())
        .filter(Boolean)
    : []

async function refresh(server = 'http://flix.lan') {
  const names = new Set()
  for (const kind of ['performers', 'studios']) {
    for (let page = 1; ; page++) {
      const res = await fetch(`${server}/api/${kind}?perPage=120&page=${page}&unblocked=1&sort=name`)
      if (!res.ok) throw new Error(`GET /api/${kind} page ${page}: ${res.status}`)
      const d = await res.json()
      const items = d.items ?? []
      for (const it of items) {
        if (it.name) names.add(it.name.trim())
        for (const a of it.aliases ?? []) if (typeof a === 'string') names.add(a.trim())
      }
      if (items.length < 120) break
    }
  }
  mkdirSync(PRIV, { recursive: true })
  const list = [...names].filter((n) => n.length >= MIN_LEN).sort()
  writeFileSync(AUTO, `# generated by privacy-check.mjs refresh from ${server} on ${new Date().toISOString().slice(0, 10)}\n${list.join('\n')}\n`)
  console.log(`private/denylist.auto.txt: ${list.length} names`)
}

function check() {
  const allow = new Set(readTerms(ALLOW))
  const terms = [...new Set([...readTerms(AUTO), ...readTerms(MANUAL)])].filter((t) => t.length >= MIN_LEN && !allow.has(t))
  if (!terms.length) {
    console.log('privacy: no denylist in private/ (fresh clone?); run `node scripts/privacy-check.mjs refresh` to build one')
    return 0
  }
  const esc = (t) => t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  // Longest first, so "Jane Doe Studio" wins over "Jane Doe".
  const re = new RegExp(`(?<![\\p{L}\\p{N}])(?:${terms.sort((a, b) => b.length - a.length).map(esc).join('|')})(?![\\p{L}\\p{N}])`, 'gu')
  const git = (args) => spawnSync('git', args, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }).stdout.split('\n').filter(Boolean)
  const files = [...new Set([...git(['ls-files']), ...git(['ls-files', '--others', '--exclude-standard'])])].filter(
    (f) => !SKIP.some((r) => r.test(f)) && existsSync(join(ROOT, f)),
  )
  const hits = []
  for (const f of files) {
    const lines = readFileSync(join(ROOT, f), 'utf8').split('\n')
    lines.forEach((line, i) => {
      for (const m of line.matchAll(re)) hits.push(`${f}:${i + 1}: ${m[0]}`)
    })
  }
  for (const h of hits) console.log(h)
  console.log(`privacy: ${files.length} files, ${terms.length} terms, ${hits.length} hit(s)`)
  return hits.length ? 1 : 0
}

const [cmd, arg] = process.argv.slice(2)
if (cmd === 'refresh') await refresh(arg)
else process.exit(check())
