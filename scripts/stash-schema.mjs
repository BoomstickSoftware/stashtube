#!/usr/bin/env node
// Refresh apps/server/stash.schema.graphql from a running Stash, so `pnpm --filter @flix/server
// codegen` can regenerate src/stash.schema.ts after a Stash upgrade.
//
//   STASH_URL=http://stash:9999 STASH_API_KEY=… node scripts/stash-schema.mjs
//   node scripts/stash-schema.mjs introspection.json   # from a saved introspection result
//
// The second form takes the `data` object of the standard introspection query (what
// scripts/stash.py prints), for when the key is not in this shell's env.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(resolve(dirname(fileURLToPath(import.meta.url)), '../apps/server/package.json'))
const { buildClientSchema, getIntrospectionQuery, printSchema } = require('graphql')

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../apps/server/stash.schema.graphql')

async function introspect() {
  const file = process.argv[2]
  if (file) return JSON.parse(readFileSync(file, 'utf8'))
  const url = process.env.STASH_URL
  const key = process.env.STASH_API_KEY
  if (!url || !key) throw new Error('set STASH_URL and STASH_API_KEY, or pass a saved introspection JSON file')
  const res = await fetch(`${url}/graphql`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', ApiKey: key },
    body: JSON.stringify({ query: getIntrospectionQuery({ descriptions: true }) }),
  })
  if (!res.ok) throw new Error(`Stash HTTP ${res.status}`)
  const body = await res.json()
  if (body.errors?.length) throw new Error(body.errors.map((e) => e.message).join('; '))
  return body.data
}

const data = await introspect()
const version = process.env.STASH_URL
  ? await fetch(`${process.env.STASH_URL}/graphql`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', ApiKey: process.env.STASH_API_KEY },
      body: JSON.stringify({ query: '{ version { version } }' }),
    })
      .then((r) => r.json())
      .then((b) => b.data?.version?.version ?? 'unknown')
  : (process.env.STASH_VERSION ?? 'unknown')
const header = `# Stash GraphQL schema, introspected from Stash ${version} on ${new Date().toISOString().slice(0, 10)}.\n# Generated by scripts/stash-schema.mjs; do not edit. src/stash.schema.ts is built from it.\n\n`
writeFileSync(out, header + printSchema(buildClientSchema(data)) + '\n')
console.log(`wrote ${out} (Stash ${version})`)
